package server

import (
	"fmt"
	"os"
	"syscall"
)

// lockFile takes an exclusive advisory lock on path (created if needed) and
// returns its release. It serializes tokens.json between the server and the
// `neofreebox token` command, which run as separate processes.
func lockFile(path string) (func(), error) {
	f, err := os.OpenFile(path, os.O_RDWR|os.O_CREATE, 0o600)
	if err != nil {
		return nil, fmt.Errorf("lock tokens: %w", err)
	}
	if err := syscall.Flock(int(f.Fd()), syscall.LOCK_EX); err != nil {
		_ = f.Close()
		return nil, fmt.Errorf("lock tokens: %w", err)
	}
	return func() {
		_ = syscall.Flock(int(f.Fd()), syscall.LOCK_UN)
		_ = f.Close()
	}, nil
}
